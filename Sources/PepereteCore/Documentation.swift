import Foundation

public enum DocumentationPublisher {
    public struct Publication: Sendable {
        public var boardID: String
        public var file: URL
        public var error: String?
    }

    public static func publish(_ database: Database) -> [Publication] {
        database.boards.compactMap { board in
            guard let settings = board.documentation, settings.enabled else { return nil }
            let folder = URL(fileURLWithPath: settings.folderPath, isDirectory: true)
            let file = folder.appendingPathComponent(settings.fileName)
            do {
                var isDirectory: ObjCBool = false
                guard FileManager.default.fileExists(atPath: folder.path, isDirectory: &isDirectory), isDirectory.boolValue else {
                    throw StoreError.invalid("Documentation folder is unavailable.")
                }
                try Data(markdown(for: board, in: database).utf8).write(to: file, options: .atomic)
                return Publication(boardID: board.id, file: file, error: nil)
            } catch {
                return Publication(boardID: board.id, file: file, error: error.localizedDescription)
            }
        }
    }

    public static func suggestedFileName(for board: Board) -> String {
        let invalid = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: " -_" )).inverted
        let cleaned = board.title.components(separatedBy: invalid).joined().trimmingCharacters(in: .whitespacesAndNewlines)
        return (cleaned.isEmpty ? "Peperete Board" : cleaned) + ".md"
    }

    public static func markdown(for board: Board, in database: Database) -> String {
        let columns = database.columns(in: board.id)
        let allCards = columns.flatMap { database.cards(in: $0.id, includeArchived: true) }
        let active = allCards.filter { !$0.archived }
        let formatter = ISO8601DateFormatter()
        var lines = [
            "# \(board.title)", "",
            "> Live project documentation generated by Peperete.",
            "> Updated: \(formatter.string(from: Date())) · Revision: \(database.revision)", "",
            "## Project status", "",
            "- Open: \(active.filter { !$0.completed }.count)",
            "- Completed: \(active.filter(\.completed).count)",
            "- Archived: \(allCards.filter(\.archived).count)", ""
        ]
        for column in columns {
            lines += ["## \(column.title)", ""]
            let cards = database.cards(in: column.id).filter { !$0.archived }
            if cards.isEmpty { lines += ["_No cards._", ""]; continue }
            for card in cards {
                lines += ["### \(card.completed ? "✅" : "⬜️") \(card.title)", ""]
                lines.append("- Status: \(card.completed ? "Completed" : "Open")")
                if let due = card.due { lines.append("- Due: \(formatter.string(from: due))") }
                lines.append("- Card ID: `\(card.id)`")
                if let source = card.sourceURL { lines.append("- Original source: \(source)") }
                if !card.notes.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                    lines += ["", card.notes, ""]
                } else { lines.append("") }
            }
        }
        let archived = allCards.filter(\.archived)
        if !archived.isEmpty {
            lines += ["## Archived", ""]
            lines += archived.map { "- \($0.completed ? "✅" : "⬜️") \($0.title)" }
            lines.append("")
        }
        let activity = database.activityLog.filter { $0.boardID == board.id }.sorted { $0.occurredAt > $1.occurredAt }
        lines += ["## Activity history", ""]
        if activity.isEmpty { lines.append("_Activity recording starts when documentation is enabled._") }
        else { lines += activity.map { "- \(formatter.string(from: $0.occurredAt)) — \($0.summary)" } }
        lines.append("")
        return lines.joined(separator: "\n")
    }
}

extension Database {
    mutating func recordChanges(from before: Database, at date: Date = Date()) {
        var additions: [Activity] = []
        let oldCards = Dictionary(uniqueKeysWithValues: before.cards.map { ($0.id, $0) })
        let oldColumns = Dictionary(uniqueKeysWithValues: before.columns.map { ($0.id, $0) })
        let newColumns = Dictionary(uniqueKeysWithValues: columns.map { ($0.id, $0) })

        for board in boards where !before.boards.contains(where: { $0.id == board.id }) {
            additions.append(Activity(boardID: board.id, summary: "Created board “\(board.title)”", occurredAt: date))
        }
        for column in columns where !before.columns.contains(where: { $0.id == column.id }) {
            additions.append(Activity(boardID: column.boardID, summary: "Added column “\(column.title)”", occurredAt: date))
        }
        for card in cards {
            guard let column = newColumns[card.columnID] else { continue }
            guard let old = oldCards[card.id] else {
                additions.append(Activity(boardID: column.boardID, cardID: card.id, summary: "Added card “\(card.title)” to \(column.title)", occurredAt: date))
                continue
            }
            if old.columnID != card.columnID {
                let oldName = oldColumns[old.columnID]?.title ?? "another column"
                additions.append(Activity(boardID: column.boardID, cardID: card.id, summary: "Moved “\(card.title)” from \(oldName) to \(column.title)", occurredAt: date))
            }
            if old.completed != card.completed {
                additions.append(Activity(boardID: column.boardID, cardID: card.id, summary: "\(card.completed ? "Completed" : "Reopened") “\(card.title)”", occurredAt: date))
            }
            if old.archived != card.archived {
                additions.append(Activity(boardID: column.boardID, cardID: card.id, summary: "\(card.archived ? "Archived" : "Restored") “\(card.title)”", occurredAt: date))
            }
            if old.title != card.title || old.notes != card.notes || old.due != card.due {
                additions.append(Activity(boardID: column.boardID, cardID: card.id, summary: "Updated “\(card.title)”", occurredAt: date))
            }
        }
        if !additions.isEmpty {
            var log = activities ?? []
            log.append(contentsOf: additions)
            activities = log
        }
    }
}
